local function AngerMonkeys(inst,worker)
	local x,y,z = inst.Transform:GetWorldPosition()
	local monkeys = TheSim:FindEntities(x,y,z,30,{"monkey"})
	if monkeys then
		for i,v in ipairs(monkeys) do
			if v.components.combat then
				v.components.combat:SuggestTarget(worker)
			end
		end
	end
end

local function OnWork(inst, worker, workleft)
	if inst.prefab == "um_slimestone_rock" then
		AngerMonkeys(inst,worker)
	end
    if workleft <= 0 then
        local pt = inst:GetPosition()
        SpawnPrefab("rock_break_fx").Transform:SetPosition(pt.x, pt.y, pt.z)
		inst.SoundEmitter:PlaySound("dontstarve/frog/splat")
        inst.components.lootdropper:DropLoot(pt)
		if inst.prefab == "um_slimestone_rock" then
			inst.components.lootdropper:SpawnLootPrefab("um_gemology_geode_slime")
		end
		inst:Remove()
    else
		inst.AnimState:PlayAnimation(
			(workleft < TUNING.ROCKS_MINE / 3 and "low") or
			(workleft < TUNING.ROCKS_MINE * 2 / 3 and "med") or
			"full"
		)
    end
end

