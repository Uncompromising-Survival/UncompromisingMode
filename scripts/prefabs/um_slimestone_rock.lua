local DAMAGE_ONEOF_TAGS = {"NPC_workable", "CHOP_workable", "HAMMER_workable", "MINE_workable", "DIG_workable" }

local function BreakStuff(inst)
	local x,y,z = inst.Transform:GetWorldPosition()
	local structure_ents = TheSim:FindEntities(x, 0, z, 2,nil,nil,DAMAGE_ONEOF_TAGS)
	for i,v in ipairs(structure_ents) do
		if v ~= inst then
			SpawnPrefab("collapse_small").Transform:SetPosition(v.Transform:GetWorldPosition())
			v.components.workable:Destroy(inst)		
		end			
	end
end

local function FreeFall(inst)
	local x, y, z = inst.Transform:GetWorldPosition()
	local scaleFactor = Lerp(.5, 1.5, y / 35)*6
	inst.shadow.Transform:SetScale(scaleFactor, scaleFactor, scaleFactor)
	if y < 0.4 then
		inst.AnimState:PlayAnimation("bounce",false)
		inst.AnimState:PushAnimation("full")
		inst.components.workable.workleft = TUNING.ROCKS_MINE
		
		inst.FallingTask:Cancel()
		inst.FallingTask = nil
		BreakStuff(inst)
		inst.shadow:Remove()
		inst.Physics:Stop()
		ChangeToObstaclePhysics(inst)

		--AXE hit players in the head
		local ents = TheSim:FindEntities(x, 0, z, 3, {"_health",})
		for i, v in ipairs(ents) do
			if v:IsValid() then 
				if v.components.sanity then
					if v.prefab == "wormwood" then
						v.components.sanity:DoDelta(33)
					else
						v.components.sanity:DoDelta(-50)
					end
				end
				v.components.combat:GetAttacked(inst, 300) --AXE Absolutely no mercy.
			end
		end		

		inst.Transform:SetPosition(x,0,z)
		SpawnPrefab("collapse_big").Transform:SetPosition(x,0,z)
	end
	
end

local function BeginFreeFall(inst)
	inst.SoundEmitter:PlaySound("dontstarve/common/meteor_spawn")
	inst.AnimState:PlayAnimation("fall")
	inst.components.workable.workleft = -1
	local x,y,z = inst.Transform:GetWorldPosition()
	MakeInventoryPhysics(inst, 1)
	inst.shadow = SpawnPrefab("warningshadow")
	inst.shadow:ListenForEvent("onremove", function(inst) inst.shadow:Remove() end, inst)
	inst.shadow.Transform:SetPosition(x, 0, z)	
	inst.FallingTask = inst:DoPeriodicTask(FRAMES,FreeFall)
	inst.shadow.AnimState:SetDeltaTimeMultiplier(0.25)
	inst.Transform:SetPosition(x,y+30,z)
end

local function mainrocks(bank)
    local inst = CreateEntity()

    inst.entity:AddTransform()
    inst.entity:AddAnimState()
    inst.entity:AddSoundEmitter()
    inst.entity:AddMiniMapEntity()
    inst.entity:AddNetwork()

    MakeObstaclePhysics(inst, 1.5)

	inst.MiniMapEntity:SetIcon("um_slimestone_rock_icon.tex")

    inst.AnimState:SetBank(bank)
    inst.AnimState:SetBuild("um_slimestone_rock")
	inst.AnimState:PlayAnimation("full")


    inst:AddTag("boulder")

    inst.entity:SetPristine()

    if not TheWorld.ismastersim then
        return inst
    end

    -- NOTE(DiogoW): Only use dependencies generated by lootdroper.
    inst.scrapbook_deps = {}

    inst:AddComponent("lootdropper")


    inst:AddComponent("workable")
    inst.components.workable:SetWorkAction(ACTIONS.MINE)
    inst.components.workable:SetWorkLeft(TUNING.ROCKS_MINE)
    inst.components.workable:SetOnWorkCallback(OnWork)
	inst.components.lootdropper:SetChanceLootTable('um_slimestone_rock')
	
    local colour = math.random(75,100)*0.01
    inst.AnimState:SetMultColour(colour, colour, colour, 1)


    inst:AddComponent("inspectable")
	
    MakeHauntableWork(inst)

	inst.Transform:SetScale(1.25,1.25,1.25)
	
	inst.BeginFreeFall = BeginFreeFall

    return inst
end

