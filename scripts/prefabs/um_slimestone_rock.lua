local function IdentifyRockDensity(inst)
	local x,y,z = inst.Transform:GetWorldPosition()
	local rocks = TheSim:FindEntities(x,y,z,64,{"boulder"})

	local gemless = {}
	local gem = {}
	for i,rock in ipairs(rocks) do
		if rock.prefab == "um_slimestone_rock" then
			table.insert(gem,rock)
		end
		if rock.prefab == "um_slimestone_rock_gemless" then
			table.insert(gemless,rock)
		end
	end
	return gemless, gem
end

local function RangeDetect(pt,ent)
	if ent:GetDistanceSqToPoint(pt) < 16 then
		return true
	else
		return false
	end
end

local function TooCloseOtherRocks(pt, gemless, gem)
	local range_detect_trigger = false
	for i,v in ipairs(gemless) do
		range_detect_trigger = RangeDetect(pt,v)
		if range_detect_trigger == true then
			return range_detect_trigger
		end
	end
	for i,v in ipairs(gem) do
		range_detect_trigger = RangeDetect(pt,v)
		if range_detect_trigger == true then --AXE Terminate early if it found something
			return range_detect_trigger
		end
	end
	return range_detect_trigger
end

local function RespawnRocks(inst)
	local gemless,gem = IdentifyRockDensity(inst)
	if (#gemless + #gem) > 12 then
		return
	end
	
	local offset = FindWalkableOffset(inst:GetPosition(), TWOPI*math.random(), math.random(4,32),64,function(pt) return not TooCloseOtherRocks(pt,gemless,gem) end)
	local prefabname = math.random() > 0.75 and #gem < 2 and "um_slimestone_rock" or "um_slimestone_rock_gemless"

	if prefabname == "um_slimestone_rock" then
		local monkeybarrel = FindEntity(inst,64,function(ent) return ent.prefab == "monkeybarrel" end,function(pt) return not TooCloseOtherRocks(pt,gemless,gem) end)
		if monkeybarrel then
			offset = FindWalkableOffset(monkeybarrel:GetPosition(), TWOPI*math.random(), math.random(4,5),6)
		end
	end

	local rock = SpawnPrefab(prefabname)
	local x,y,z = inst.Transform:GetWorldPosition()
	rock.Transform:SetPosition(x+offset.x,y,z+offset.z)

	if inst.entity:IsAwake() then --AXE Only trigger the falling sequence if the rock is awake
		rock.BeginFreeFall(rock)
	else
		BreakStuff(inst) -- AXE However... still break stuff nearby as if it did fall.
	end
end

local function fnnode()
    local inst = CreateEntity()

    inst.entity:AddTransform()
    inst.entity:AddNetwork()
    inst.entity:SetPristine()

    if not TheWorld.ismastersim then
        return inst
    end
	
    inst:ListenForEvent("startquake", function()
		if TheWorld.state.nightmarephase == "wild" then
			inst:DoTaskInTime(math.random(4,10),function(inst)
				RespawnRocks(inst)
			end)
		end
    end, TheWorld.net)			
	
	inst.RespawnRocks = RespawnRocks --AXE For calling during testing
    return inst
end

